-- Clear the Stack arcade high-score ledger.
-- A finished host-controlled game writes score entries in the same transaction
-- as the authoritative room's final state update (not a second browser POST).
create table if not exists public.ppl_clear_stack_scores (
  id bigint generated by default as identity primary key,
  source_room_id uuid not null,
  finish_version integer not null check (finish_version >= 0),
  player_index integer not null check (player_index >= 0),
  host_key text not null,
  account_key text,
  player_name text not null check (char_length(player_name) between 1 and 50),
  distance integer not null check (distance between 1 and 100),
  stack_size integer not null check (stack_size between 1 and 100),
  score numeric(8,1) not null,
  remaining integer not null check (remaining between 0 and 100),
  rounds jsonb not null default '[]'::jsonb,
  played_at timestamptz not null default now(),
  is_ranked boolean not null default true,
  constraint ppl_clear_stack_scores_source_unique unique (source_room_id, finish_version, player_index)
);

create index if not exists ppl_clear_stack_scores_global_idx
  on public.ppl_clear_stack_scores (distance, stack_size, played_at desc, score desc)
  where is_ranked;
create index if not exists ppl_clear_stack_scores_host_idx
  on public.ppl_clear_stack_scores (host_key, distance, stack_size, score desc);
create index if not exists ppl_clear_stack_scores_account_idx
  on public.ppl_clear_stack_scores (account_key, distance, stack_size, score desc);

alter table public.ppl_clear_stack_scores enable row level security;
revoke all on public.ppl_clear_stack_scores from anon, authenticated;
grant select, insert on public.ppl_clear_stack_scores to service_role;
grant usage, select on sequence public.ppl_clear_stack_scores_id_seq to service_role;

create or replace function public.ppl_clear_stack_capture_scores()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if new.game_state->>'phase' <> 'finished'
      or new.host_session_id is null
      or new.spectator_token is null
      or jsonb_typeof(new.game_state->'players') <> 'array'
  then return new;
  end if;

  -- Only the transition to a finished game counts. A replay later has a new
  -- final state version. An explicit End Game must never write duplicates.
  if tg_op = 'UPDATE' and old.game_state->>'phase' = 'finished' then
    return new;
  end if;

  insert into public.ppl_clear_stack_scores (
    source_room_id, finish_version, player_index, host_key, account_key,
    player_name, distance, stack_size, score, remaining, rounds,
    played_at, is_ranked
  )
  select
    new.id, new.state_version, (player.ordinality - 1)::integer,
    new.host_session_id,
    case when player.ordinality = 1 and new.host_session_id <> 'builder-access'
      then new.host_session_id else null end,
    left(coalesce(nullif(btrim(player.value->>'name'), ''), 'Player'), 50),
    new.distance, new.stack_size,
    (player.value->>'score')::numeric(8,1),
    (player.value->>'remaining')::integer,
    coalesce(player.value->'rounds', '[]'::jsonb),
    now(), new.host_session_id <> 'builder-access'
  from jsonb_array_elements(new.game_state->'players') with ordinality as player(value, ordinality)
  on conflict (source_room_id, finish_version, player_index) do nothing;

  return new;
end;
$$;

drop trigger if exists ppl_clear_stack_capture_scores_on_finish on public.ppl_clear_stack_rooms;
create trigger ppl_clear_stack_capture_scores_on_finish
after update of game_state on public.ppl_clear_stack_rooms
for each row
when (new.status = 'finished')
execute function public.ppl_clear_stack_capture_scores();

-- Recover the latest completed result for any previously finished room.
-- Earlier rematches are not reconstructed when their snapshots were overwritten.
insert into public.ppl_clear_stack_scores (
  source_room_id, finish_version, player_index, host_key, account_key,
  player_name, distance, stack_size, score, remaining, rounds, played_at, is_ranked
)
select r.id, r.state_version, (p.ordinality - 1)::integer, r.host_session_id,
  case when p.ordinality = 1 and r.host_session_id <> 'builder-access'
    then r.host_session_id else null end,
  left(coalesce(nullif(btrim(p.value->>'name'), ''), 'Player'), 50),
  r.distance, r.stack_size, (p.value->>'score')::numeric(8,1),
  (p.value->>'remaining')::integer, coalesce(p.value->'rounds','[]'::jsonb),
  r.updated_at, r.host_session_id <> 'builder-access'
from public.ppl_clear_stack_rooms as r
cross join lateral jsonb_array_elements(r.game_state->'players') with ordinality as p(value, ordinality)
where r.game_state->>'phase' = 'finished'
  and r.host_session_id is not null
  and r.spectator_token is not null
  and jsonb_typeof(r.game_state->'players') = 'array'
on conflict (source_room_id, finish_version, player_index) do nothing;
